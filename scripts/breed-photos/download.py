"""Download chosen photos, resize, save under public/breeds, and write photos.generated.ts.
Usage: download.py <scratch dir> <site dir>. Reads final.json: slug -> info (from found/candidates)."""
import io, json, os, sys, time, urllib.request
from concurrent.futures import ThreadPoolExecutor
from PIL import Image, ImageOps

OUT, SITE = sys.argv[1], sys.argv[2]
breeds = {b["slug"]: b for b in json.load(open(OUT + "/breeds.json"))}
final = json.load(open(OUT + "/final.json"))
UA = {"User-Agent": "HushkuBreedImages/1.0 (https://hushku.app; hello@hushku.app)"}


def fetch(slug):
    info = final[slug]
    animal = breeds[slug]["animal"]
    dest = f"{SITE}/public/breeds/{animal}/{slug}.jpg"
    for attempt in range(4):
        try:
            data = urllib.request.urlopen(urllib.request.Request(info["thumb"], headers=UA), timeout=60).read()
            im = ImageOps.exif_transpose(Image.open(io.BytesIO(data))).convert("RGB")
            im.thumbnail((1200, 1200))
            im.save(dest, "JPEG", quality=82, optimize=True, progressive=True)
            return slug, True
        except Exception as e:
            time.sleep(3 * (attempt + 1))
    return slug, False


with ThreadPoolExecutor(4) as ex:
    ok = dict(ex.map(fetch, final))

# Remove old photos we are not replacing: they were unverified and often the wrong breed.
for slug, b in breeds.items():
    path = f"{SITE}/public/breeds/{b['animal']}/{slug}.jpg"
    if not ok.get(slug) and os.path.exists(path):
        os.remove(path)

esc = lambda s: json.dumps(s, ensure_ascii=False)
lines = ["/* Generated by the breed photo script from Wikimedia Commons. Do not edit by hand. */", 'import type { PhotoCredit } from "./photos";', "export const PHOTOS: Record<string, PhotoCredit> = {"]
for slug in sorted(final):
    if not ok.get(slug):
        continue
    i, a = final[slug], breeds[slug]["animal"]
    lines.append(f'  {esc(a + "/" + slug)}: {{ src: {esc(f"/breeds/{a}/{slug}.jpg")}, artist: {esc(i["artist"])}, license: {esc(i["license"])}, licenseUrl: {esc(i.get("licenseUrl") or "")}, source: {esc(i["source"])} }},')
lines.append("};")
open(f"{SITE}/app/data/breeds/photos.generated.ts", "w").write("\n".join(lines) + "\n")
print("saved", sum(ok.values()), "failed", [s for s, v in ok.items() if not v])
