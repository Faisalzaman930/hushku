"""Copy reviewed, approved staged photos into the site and regenerate photos.generated.ts.
Approved = in reviewed.txt and not in review.json rejects. Credits come from found.json or chosen.json."""
import json, os, shutil, sys
OUT, SITE = sys.argv[1], sys.argv[2]
breeds = {b["animal"] + "-" + b["slug"]: b for b in json.load(open(OUT + "/breeds.json"))}
found = json.load(open(OUT + "/found.json"))
chosen = json.load(open(OUT + "/chosen.json")) if os.path.exists(OUT + "/chosen.json") else {}
rej = json.load(open(OUT + "/review.json"))["reject"]
reviewed = [f for f in open(OUT + "/reviewed.txt").read().split() if f]
gen = SITE + "/app/data/breeds/photos.generated.ts"
existing = {}
if os.path.exists(OUT + "/published.json"):
    existing = json.load(open(OUT + "/published.json"))
for f in reviewed:
    key = f[:-4].split("~")[0]
    if key in rej and f[:-4] != chosen.get(key, {}).get("staged"):
        continue
    b = breeds.get(key)
    if not b:
        continue
    slug = b["slug"]
    if key in chosen:
        if f[:-4] != chosen[key]["staged"]:
            continue
        info = chosen[key]
    elif "~" in f or slug not in found:
        continue
    else:
        info = found[slug]
    shutil.copyfile(f"{OUT}/staged/{f}", f"{SITE}/public/breeds/{b['animal']}/{slug}-wm.jpg")
    old = f"{SITE}/public/breeds/{b['animal']}/{slug}.jpg"
    if os.path.exists(old):
        os.remove(old)
    existing[f"{b['animal']}/{slug}"] = {"src": f"/breeds/{b['animal']}/{slug}-wm.jpg", "artist": info["artist"], "license": info["license"], "licenseUrl": info.get("licenseUrl") or "", "source": info["source"]}
json.dump(existing, open(OUT + "/published.json", "w"), indent=1)
esc = lambda s: json.dumps(s, ensure_ascii=False)
lines = ["/* Generated by scripts/breed-photos from Wikimedia Commons. Do not edit by hand. */", 'import type { PhotoCredit } from "./photos";', "export const PHOTOS: Record<string, PhotoCredit> = {"]
for k in sorted(existing):
    v = existing[k]
    lines.append(f"  {esc(k)}: {{ src: {esc(v['src'])}, artist: {esc(v['artist'])}, license: {esc(v['license'])}, licenseUrl: {esc(v['licenseUrl'])}, source: {esc(v['source'])} }},")
lines.append("};")
open(gen, "w").write("\n".join(lines) + "\n")
print("published", len(existing))
